import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { render } from '../lib/render.js'
import { fnv } from '../test/helpers/fnv.js'

// Rerun only for an intended change to the drawing, after looking at the charts it renders.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'test/fixtures/specs')

const cases = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((file) => {
    const spec = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'))
    const dark = render(spec, { theme: 'dark' })
    const light = render(spec, { theme: 'light' })
    return { name: file.slice(0, -'.json'.length), spec, dark: fnv(dark), light: fnv(light) }
  })

const out = `// Generated by scripts/snapshots.mjs.\nexport default ${JSON.stringify(cases, null, 2)}\n`
fs.writeFileSync(path.join(root, 'test/fixtures/snapshots.js'), out)
console.log(`[snapshots] ${cases.length} specs, two themes each`)
