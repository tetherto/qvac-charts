import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'
import { Chart } from '../index.ts'
import { maps } from '../maps.ts'
import { fnv } from '../test/helpers/fnv.ts'

// Rerun only for an intended change to the drawing, after looking at the charts it renders.

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const dir = path.join(root, 'test/fixtures/specs')

const cases = fs
  .readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((file) => {
    const spec = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'))
    const dark = Chart.from(spec, { maps }).toSVG({ theme: 'dark' })
    const light = Chart.from(spec, { maps }).toSVG({ theme: 'light' })
    return { name: file.slice(0, -'.json'.length), spec, dark: fnv(dark), light: fnv(light) }
  })

const out = `// Generated by scripts/snapshots.mjs.\nimport type { Spec } from '../../index.ts'\n\nexport interface Case {\n  name: string\n  spec: Spec\n  dark: string\n  light: string\n}\n\nexport const cases: ReadonlyArray<Case> = ${JSON.stringify(cases, null, 2)}\n`
fs.writeFileSync(path.join(root, 'test/fixtures/snapshots.ts'), out)
console.log(`[snapshots] ${cases.length} specs, two themes each`)
