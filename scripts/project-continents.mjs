// Regenerates lib/maps/continents/: npm run build:continents
import { createHash } from 'node:crypto'
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { geoAzimuthalEqualArea, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'
import { topology } from 'topojson-server'
import { presimplify, quantile, simplify } from 'topojson-simplify'
import { aliases as worldAliases } from '../lib/maps/aliases.ts'
import { drop, rename } from './world-names.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'lib/maps/continents')
const SOURCE = {
  url: 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_admin_0_countries.geojson',
  sha256: '3e458fc036ad0a66411f2c1e6cac49c5d7bfb81cb1123bc513b22511a2b7fdeb'
}

// Each continent is drawn in a box of [west, south, east, north], so Russia's east stays off Europe.
const CONTINENTS = {
  africa: { name: 'Africa', box: [-20, -36, 55, 38] },
  asia: { name: 'Asia', box: [25, -11, 150, 56] },
  europe: { name: 'Europe', box: [-25, 34, 45, 71] },
  'north-america': { name: 'North America', box: [-170, 5, -50, 75] },
  oceania: { name: 'Oceania', box: [110, -48, 180, -5] },
  'south-america': { name: 'South America', box: [-92, -56, -33, 13] }
}
const NAMES = ['NAME_LONG', 'NAME_EN', 'NAME_PT', 'NAME_ES', 'NAME_FR', 'NAME_DE', 'NAME_IT']
const CODES = ['ISO_A2_EH', 'ISO_A3_EH']
const SIDE = 936
const KEEP = 0.08
// An island smaller than this many square pixels is not drawn; its country keeps its mainland.
const SPECK = 6

const countries = (await source()).features.filter(
  (f) => !drop.has(f.properties.NAME) && !f.properties.CONTINENT.startsWith('Seven seas')
)

mkdirSync(out, { recursive: true })

const members = {}

for (const [id, continent] of Object.entries(CONTINENTS)) {
  const map = draw(continent)
  const body = `// Generated by scripts/project-continents.mjs from Natural Earth admin-0 (public domain).\nexport const map = ${JSON.stringify(map)}\n`

  members[id] = spellingsOf(map)
  writeFileSync(path.join(out, `${id}.ts`), body)
  console.log(
    id,
    map.regions.length,
    `${map.width}x${map.height}`,
    `${Math.round(body.length / 1024)} KB`
  )
}

writeFileSync(path.join(out, 'index.ts'), index(members))

// The Natural Earth file is fetched once into .cache and checked against its hash.
async function source() {
  const file = path.join(root, '.cache', path.basename(SOURCE.url))

  if (!existsSync(file)) {
    mkdirSync(path.dirname(file), { recursive: true })
    const res = await fetch(SOURCE.url)

    writeFileSync(file, new Uint8Array(await res.arrayBuffer()))
  }

  const sum = createHash('sha256').update(readFileSync(file)).digest('hex')

  if (sum !== SOURCE.sha256) {
    throw new Error(`${file} is not the pinned Natural Earth release (sha256 ${sum})`)
  }

  return JSON.parse(readFileSync(file, 'utf8'))
}

function draw({ name, box }) {
  const inside = countries.filter((f) => belongs(f, { name, box }))
  const shown = countries.filter((f) => touches(f, box))
  const projection = geoAzimuthalEqualArea().rotate([
    -(box[0] + box[2]) / 2,
    -(box[1] + box[3]) / 2
  ])
  const frame = outline(box)

  projection.fitWidth(SIDE, frame)

  const [[x0, y0], [x1, y1]] = geoPath(projection).bounds(frame)
  const scale = SIDE / Math.max(x1 - x0, y1 - y0)
  const [tx, ty] = projection.translate()

  projection.scale(projection.scale() * scale).translate([(tx - x0) * scale, (ty - y0) * scale])

  const width = Math.round((x1 - x0) * scale)
  const height = Math.round((y1 - y0) * scale)

  projection.clipExtent([
    [0, 0],
    [width, height]
  ])

  const path = geoPath(projection)
  const thin = thinned(shown)
  const regions = shown.flatMap((f, i) => {
    const shape = withoutSpecks(feature(thin, thin.objects.countries.geometries[i]), path)
    const d = geoPath(projection).digits(1)(shape)

    if (!d || !inside.includes(f)) {
      return d ? [{ name: canonical(f), d, cx: -1, cy: -1 }] : []
    }

    const [cx, cy] = path.centroid(largest(shape, path)).map((v) => Math.round(v))

    return [{ name: canonical(f), d, cx, cy }]
  })

  return {
    width,
    height,
    regions,
    aliases: Object.fromEntries(inside.map((f) => [canonical(f), spellings(f)]))
  }
}

// A continent's countries, and those labelled inside its box: Russia and Turkey are in two.
function belongs(f, { name, box }) {
  const { CONTINENT, LABEL_X, LABEL_Y } = f.properties

  return CONTINENT === name || within([LABEL_X, LABEL_Y], box)
}

function touches(f, box) {
  const [[w, s], [e, n]] = geoBoundsOf(f)

  return w <= box[2] && e >= box[0] && s <= box[3] && n >= box[1]
}

function within([x, y], [w, s, e, n]) {
  return x >= w && x <= e && y >= s && y <= n
}

function geoBoundsOf(f) {
  const points = coordinates(f.geometry)

  return [
    [Math.min(...points.map((p) => p[0])), Math.min(...points.map((p) => p[1]))],
    [Math.max(...points.map((p) => p[0])), Math.max(...points.map((p) => p[1]))]
  ]
}

function coordinates(geometry) {
  return geometry.type === 'Polygon' ? geometry.coordinates.flat() : geometry.coordinates.flat(2)
}

// The box as a polygon dense enough that its parallels curve as they do on the map.
function outline([w, s, e, n]) {
  const steps = (from, to) =>
    Array.from({ length: Math.abs(to - from) + 1 }, (_, i) => from + Math.sign(to - from) * i)
  const ring = [
    ...steps(w, e).map((x) => [x, s]),
    ...steps(s, n).map((y) => [e, y]),
    ...steps(e, w).map((x) => [x, n]),
    ...steps(n, s).map((y) => [w, y])
  ]

  return { type: 'Polygon', coordinates: [ring.reverse()] }
}

// The countries in one topology, so neighbours share one simplified border.
function thinned(features) {
  const topo = presimplify(topology({ countries: { type: 'FeatureCollection', features } }))

  return simplify(topo, quantile(topo, KEEP))
}

function withoutSpecks(f, path) {
  if (f.geometry.type !== 'MultiPolygon') {
    return f
  }

  const sizes = f.geometry.coordinates.map((c) => path.area({ type: 'Polygon', coordinates: c }))
  const top = Math.max(...sizes)
  const kept = f.geometry.coordinates.filter((_, i) => sizes[i] >= SPECK || sizes[i] === top)

  return { ...f, geometry: { type: 'MultiPolygon', coordinates: kept } }
}

// The polygon a country is labelled on, so France's value sits in France, not overseas.
function largest(f, path) {
  if (f.geometry.type !== 'MultiPolygon') {
    return f
  }

  const polys = f.geometry.coordinates.map((c) => ({ type: 'Polygon', coordinates: c }))

  return polys.reduce((a, b) => (path.area(a) >= path.area(b) ? a : b))
}

function canonical(f) {
  return rename[f.properties.NAME] ?? f.properties.NAME
}

// Every name Natural Earth knows a country by, in the languages a user is likely to write.
function spellings(f) {
  const name = canonical(f)
  const p = f.properties
  const all = [
    p.NAME,
    ...NAMES.map((k) => p[k]),
    ...CODES.map((k) => p[k]).filter((c) => c && c !== '-99'),
    ...(worldAliases[name] ?? [])
  ]

  return [...new Set(all.filter((n) => n && n !== name))]
}

// Same folding as lib/places.ts, so the index matches what the renderer looks up.
function key(s) {
  return s.normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim()
}

function spellingsOf(map) {
  const names = Object.entries(map.aliases).flatMap(([name, others]) => [name, ...others])

  return [...new Set(names.map(key))]
}

function index(byContinent) {
  const loaders = Object.keys(CONTINENTS)
    .map((id) => `  '${id}': () => import('./${id}.ts').then((m) => m.map)`)
    .join(',\n')

  return `// Generated by scripts/project-continents.mjs.
import type { GeoMap } from '../../places.ts'

// Every spelling of each continent's countries, so a host loads the one continent it needs.
export const members: Readonly<Record<string, ReadonlyArray<string>>> = ${JSON.stringify(byContinent)}

export const loaders: Readonly<Record<string, () => Promise<GeoMap>>> = {
${loaders}
}
`
}
